#!/usr/bin/env node
// Turns a folder of single-colour illustrations (EPS, PDF or PNG) into the web
// artwork a public guide design uses.
//
//   node scripts/convert-guide-artwork.mjs <course-slug> <source-folder>
//   node scripts/convert-guide-artwork.mjs alivingunion ~/Documents/Flowers-eps
//
// For each file it writes static/guides/<slug>/artwork/<name>.webp (transparent
// background, ink as the opaque part) and regenerates
// src/lib/public-guides/<slug>/artwork.ts. The pages draw these through
// GuideArtwork.svelte, which uses the image as a mask and colours it from the theme,
// so the source colour does not matter.
//
// Needs Ghostscript (`gs`) for EPS/PDF and `cwebp`: brew install ghostscript webp

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [slug, sourceArg] = process.argv.slice(2);
if (!slug || !sourceArg) {
	console.error('Usage: node scripts/convert-guide-artwork.mjs <course-slug> <source-folder>');
	process.exit(1);
}

const repo = resolve(fileURLToPath(import.meta.url), '../..');
const source = resolve(sourceArg.replace(/^~/, process.env.HOME ?? '~'));
const designDir = join(repo, 'src/lib/public-guides', slug);
const outDir = join(repo, 'static/guides', slug, 'artwork');
const MAX_SIDE = 1400; // px on the longer side — plenty for a margin illustration at 2x

if (!existsSync(designDir)) {
	console.error(`No guide design at src/lib/public-guides/${slug} — create it first.`);
	process.exit(1);
}

const files = readdirSync(source)
	.filter((f) => ['.eps', '.pdf', '.png'].includes(extname(f).toLowerCase()))
	.sort();
if (files.length === 0) {
	console.error(`No .eps, .pdf or .png files in ${source}`);
	process.exit(1);
}

const slugify = (name) => name.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const dimensions = (file) => {
	const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' });
	return { width: Number(/pixelWidth: (\d+)/.exec(out)[1]), height: Number(/pixelHeight: (\d+)/.exec(out)[1]) };
};

mkdirSync(outDir, { recursive: true });
const work = mkdtempSync(join(tmpdir(), 'guide-artwork-'));
const entries = [];
const skipped = [];

for (const file of files) {
	const input = join(source, file);
	const name = basename(file, extname(file));
	const key = slugify(name);

	if (statSync(input).size === 0) {
		skipped.push(`${file} (empty file — still copying or not downloaded?)`);
		continue;
	}

	try {
		let png = input;
		if (extname(file).toLowerCase() !== '.png') {
			png = join(work, `${key}.png`);
			execFileSync('gs', ['-q', '-dSAFER', '-dBATCH', '-dNOPAUSE', '-dEPSCrop', '-sDEVICE=pngalpha', '-r300', '-dTextAlphaBits=4', '-dGraphicsAlphaBits=4', `-sOutputFile=${png}`, input]);
		}
		const { width, height } = dimensions(png);
		const scale = Math.min(1, MAX_SIDE / Math.max(width, height));
		const w = Math.round(width * scale);
		const h = Math.round(height * scale);
		const out = join(outDir, `${key}.webp`);
		execFileSync('cwebp', ['-quiet', '-q', '80', '-alpha_q', '100', '-resize', String(w), String(h), png, '-o', out]);
		entries.push({ key, name, src: `/guides/${slug}/artwork/${key}.webp`, width: w, height: h });
		console.log(`✓ ${file} → ${key}.webp (${w}×${h}, ${Math.round(statSync(out).size / 1024)} KB)`);
	} catch (err) {
		skipped.push(`${file} (${String(err.message).split('\n')[0]})`);
	}
}
rmSync(work, { recursive: true, force: true });

if (entries.length === 0) {
	console.error('\nNothing converted, so artwork.ts was left as it is.');
	for (const s of skipped) console.error(`  skipped ${s}`);
	process.exit(1);
}

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const manifest = `// GENERATED by scripts/convert-guide-artwork.mjs — do not edit by hand.
// Re-run the script to add or update illustrations.

export interface GuideArtworkFile {
	name: string;
	src: string;
	width: number;
	height: number;
}

export const ARTWORK: Record<string, GuideArtworkFile> = {
${entries.map((e) => `\t${quote(e.key)}: { name: ${quote(e.name)}, src: ${quote(e.src)}, width: ${e.width}, height: ${e.height} }`).join(',\n')}
};
`;
writeFileSync(join(designDir, 'artwork.ts'), manifest);

console.log(`\n${entries.length} illustration(s) written to static/guides/${slug}/artwork and listed in src/lib/public-guides/${slug}/artwork.ts`);
if (skipped.length > 0) {
	console.log(`${skipped.length} skipped:`);
	for (const s of skipped) console.log(`  ${s}`);
}
